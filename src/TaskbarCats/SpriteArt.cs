    /// Belly stage 1-2 (Tune.BellyStage): the lowest torso row (K, six or more fur, K) is doubled `stage` times and
    /// everything above it moves up. No room at the top, or no torso row: the frame is returned unchanged.
    public static string[] Chubby(string[] rows, int stage)
    {
        if (stage <= 0 || rows.Take(stage).Any(r => r.Any(ch => ch != '.'))) return rows;
        int y = Array.FindLastIndex(rows, r => System.Text.RegularExpressions.Regex.IsMatch(r, "K[FDL]{6,}K"));
        if (y < stage) return rows;
        return [.. rows[stage..(y + 1)], .. Enumerable.Repeat(rows[y], stage), .. rows[(y + 1)..]];
    }

